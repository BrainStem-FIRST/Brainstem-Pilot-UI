import { getProjectDir, loadAppSettingsFromProject, loadVariantsFromProject, safeNameFromString } from './projectFolder.js';

const JAVA_PACKAGE = 'org.firstinspires.ftc.teamcode.brainstemPilotAuto.opmodeAutos';
const OPMODE_DIR = 'opmodeAutos';
const GENERATED_MARKER = 'AUTO-GENERATED by Brainstem Pilot UI';

/** Hand-maintained Java files in opmodeAutos — never deleted by sync. */
const STATIC_JAVA_FILES = new Set([]);

export function variantNameToClassName(displayName) {
  const parts = (displayName ?? '')
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean);

  if (parts.length === 0) {
    return 'VariantAuto';
  }

  let merged = parts
    .map(part => {
      if (/^\d+$/.test(part)) return part;
      return part.charAt(0).toUpperCase() + part.slice(1);
    })
    .join('');

  // Java class names cannot start with a digit — prefix with '_' only when required.
  if (!/^[A-Za-z_]/.test(merged)) {
    merged = `_${merged}`;
  }
  if (!merged.endsWith('Auto')) {
    merged += 'Auto';
  }
  return merged;
}

function escapeJavaString(value) {
  return (value ?? '').replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

export function buildFtcOpmodeJavaContent(displayName) {
  const className = variantNameToClassName(displayName);
  const variantId = safeNameFromString(displayName);
  const escapedName = escapeJavaString(displayName);

  return `package ${JAVA_PACKAGE};

import com.qualcomm.robotcore.eventloop.opmode.Autonomous;
import org.firstinspires.ftc.teamcode.utils.pilotAutoBuilder.PilotAutoBase;

/**
 * ${GENERATED_MARKER} — do not edit manually.
 * Variant: ${displayName}
 */
@Autonomous(name = "${escapedName}", group = "Pilot")
public class ${className} extends PilotAutoBase {
    public ${className}() {
        super("${variantId}");
    }
}
`;
}

export function ftcOpmodeJavaFilename(displayName) {
  return `${variantNameToClassName(displayName)}.java`;
}

async function isFtcProject() {
  const settings = await loadAppSettingsFromProject();
  return settings?.projectType === 'ftc';
}

async function getOpmodeAutosDir() {
  const root = getProjectDir();
  if (!root) return null;
  return root.getDirectoryHandle(OPMODE_DIR, { create: true });
}

async function writeOpmodeJavaFile(displayName) {
  const dir = await getOpmodeAutosDir();
  if (!dir || !displayName?.trim()) return;

  const filename = ftcOpmodeJavaFilename(displayName);
  const content = buildFtcOpmodeJavaContent(displayName.trim());
  const fh = await dir.getFileHandle(filename, { create: true });
  const writable = await fh.createWritable();
  await writable.write(content);
  await writable.close();
}

async function deleteOpmodeJavaFile(displayName) {
  const dir = await getOpmodeAutosDir();
  if (!dir || !displayName?.trim()) return;

  const filename = ftcOpmodeJavaFilename(displayName);
  try {
    await dir.removeEntry(filename);
  } catch {
    /* ignore missing file */
  }
}

async function isGeneratedOpmodeFile(dir, filename) {
  if (!filename.endsWith('.java') || STATIC_JAVA_FILES.has(filename)) {
    return false;
  }
  try {
    const fh = await dir.getFileHandle(filename);
    const text = await (await fh.getFile()).text();
    return text.includes(GENERATED_MARKER);
  } catch {
    return false;
  }
}

/** Create or update one FTC OpMode Java file for a variant. */
export async function syncFtcOpmodeAuto(variantObj, previousName = null) {
  if (!(await isFtcProject())) return;
  if (!variantObj?.name?.trim()) return;

  if (previousName && previousName.trim() && previousName.trim() !== variantObj.name.trim()) {
    await deleteOpmodeJavaFile(previousName.trim());
  }

  await writeOpmodeJavaFile(variantObj.name.trim());
}

/** Remove the FTC OpMode Java file for a deleted variant. */
export async function deleteFtcOpmodeAuto(displayName) {
  if (!(await isFtcProject())) return;
  if (!displayName?.trim()) return;
  await deleteOpmodeJavaFile(displayName.trim());
}

/** Regenerate all FTC OpMode files from variants/ and remove stale generated files. */
export async function syncAllFtcOpmodeAutos() {
  if (!(await isFtcProject())) return;

  const variants = (await loadVariantsFromProject()) ?? [];
  const expectedFiles = new Set(
    variants
      .filter(v => v?.name?.trim())
      .map(v => ftcOpmodeJavaFilename(v.name.trim()))
  );

  for (const variant of variants) {
    if (variant?.name?.trim()) {
      await writeOpmodeJavaFile(variant.name.trim());
    }
  }

  const dir = await getOpmodeAutosDir();
  if (!dir) return;

  for await (const entry of dir.values()) {
    if (entry.kind !== 'file' || !entry.name.endsWith('.java')) continue;
    if (STATIC_JAVA_FILES.has(entry.name)) continue;
    if (expectedFiles.has(entry.name)) continue;
    if (await isGeneratedOpmodeFile(dir, entry.name)) {
      try {
        await dir.removeEntry(entry.name);
      } catch {
        /* ignore */
      }
    }
  }
}
